#!/usr/bin/env python3
"""Write docs/awt.1 and docs/reference/*.md from the awt parser and its CLI_HELP table.

    python3 tools/gen_docs.py          write the files
    python3 tools/gen_docs.py --check  exit 1 if a file differs (tests/test_docs.py does the same, in process)

`awt --help` and `awt VERB --help` come from the same two sources, so help, man page and reference cannot drift.
Standard library only; the output does not depend on the Python version.
"""
import importlib.machinery, importlib.util, os, sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def load_awt():
    loader = importlib.machinery.SourceFileLoader("awt_mod", os.path.join(REPO, "awt"))
    m = importlib.util.module_from_spec(importlib.util.spec_from_loader("awt_mod", loader))
    loader.exec_module(m)
    return m


def entries(m):
    """(key, parser) for every documented command: each verb, then each effect step."""
    sp = m.build()._subparsers._group_actions[0].choices
    out = []
    for name, q in sp.items():
        out.append((name, q))
        if name == "effect":
            out += [("effect " + n, c) for n, c in q._subparsers._group_actions[0].choices.items() if "effect " + n in m.CLI_HELP]
    return [(k, q) for k, q in out if k in m.CLI_HELP]


def args_of(q):
    """(positionals, options) as (token, help text) pairs; tokens are ARG or --flag [VALUE]."""
    pos, opt = [], []
    for a in q._actions:
        if a.help in (None, "==SUPPRESS==") or a.dest == "help" or a.help == "show this help message and exit":
            continue
        if a.option_strings:
            f = a.option_strings[0]
            v = "" if a.nargs == 0 else " " + (a.metavar or a.dest.replace("from_", "from").upper())
            opt.append((f + v, f, a.help, a.required))
        else:
            tok = "|".join(a.choices) if a.choices and a.dest in ("status", "value") else a.dest.upper()
            pos.append((tok, a.dest.upper(), a.help, a.nargs not in ("?", None)))
    return pos, opt


def synopsis(key, q):
    pos, opt = args_of(q)
    s = "awt " + key
    for tok, _, _, req in opt:
        s += " " + (tok if req else "[%s]" % tok)
    for tok, name, _, _ in pos:
        s += " " + (name if tok == name else tok)
    return s


def slug(key):
    return key.replace(" ", "-")


def reference(m, key, q):
    summary = m.CLI_HELP[key][0]
    pos, opt = args_of(q)
    L = ["# awt %s" % key, "", summary, "", "```", synopsis(key, q), "```", ""]
    if pos:
        L += ["## Arguments", "", "| Argument | Meaning |", "|---|---|"] + ["| `%s` | %s |" % (n, h) for _, n, h, _ in pos] + [""]
    if opt:
        L += ["## Flags", "", "| Flag | Meaning |", "|---|---|"] + ["| `%s` | %s |" % (t, h) for t, _, h, _ in opt] + [""]
    if key == "effect":
        L += ["## Steps", ""] + ["- [`awt effect %s`](effect-%s.md): %s" % (n, n, m.CLI_HELP["effect " + n][0]) for n in ("plan", "begin", "mark", "show")] + [""]
    L += ["Global flags `--dir`, `--by` and `--model` work with every verb. Exit codes: 0 ok, 1 refused, 2 usage, 3 permissions, 4 no task or id.", "",
          "Generated by `tools/gen_docs.py` from the table behind `awt %s --help`; do not edit.\n" % key]
    return "\n".join(L)


def index(m, ents):
    L = ["# awt reference", "", "One page per verb. Start with [concepts](../concepts.md); `awt --help` prints the same list.", "",
         "| Verb | What it does |", "|---|---|"]
    L += ["| [`%s`](%s.md) | %s |" % (k, slug(k), m.CLI_HELP[k][0]) for k, _ in ents]
    L += ["", "Global flags: " + "; ".join("`%s` %s" % (f, h) for f, h in m.GLOBAL_HELP) + ".", "",
          "Generated by `tools/gen_docs.py`; do not edit.\n"]
    return "\n".join(L)


def esc(t):
    return t.replace("\\", "\\\\").replace("-", "\\-")


def manpage(m, ents):
    L = ['.TH AWT 1 "" "awt %s" "User Commands"' % m.VERSION, ".SH NAME", "awt \\- a memory for AI agents that lives in plain files",
         ".SH SYNOPSIS", ".B awt", "[global flags] VERB [ARGS]", ".SH DESCRIPTION",
         "awt records decisions, questions, links and handoffs for an agent task in plain files, and recalls them in the next session.",
         "It never runs a command it is asked to track. See SPEC.md and docs/concepts.md in the repository.", ".SH GLOBAL FLAGS"]
    for f, h in m.GLOBAL_HELP:
        L += [".TP", ".B " + esc(f), esc(h)]
    L.append(".SH VERBS")
    for k, q in ents:
        pos, opt = args_of(q)
        L += [".SS " + esc(k), esc(m.CLI_HELP[k][0]), ".PP", ".B " + esc(synopsis(k, q))]
        for tok, name, h, _ in pos:
            L += [".TP", ".B " + esc(name), esc(h)]
        for tok, f, h, _ in opt:
            L += [".TP", ".B " + esc(tok), esc(h)]
    L += [".SH EXIT STATUS", "0 ok, 1 refused, 2 usage error, 3 permission denied, 4 no task or id.", ".SH SEE ALSO",
          "docs/reference/ in the repository, one page per verb; `awt help agents`.", ""]
    return "\n".join(L)


def render(m=None):
    """{relative path: text} for every generated file."""
    m = m or load_awt()
    ents = entries(m)
    files = {"docs/awt.1": manpage(m, ents), "docs/reference/index.md": index(m, ents)}
    for k, q in ents:
        files["docs/reference/%s.md" % slug(k)] = reference(m, k, q)
    return files


def main(argv):
    files = render()
    bad = []
    for rel, text in files.items():
        p = os.path.join(REPO, rel)
        if "--check" in argv:
            if not os.path.isfile(p) or open(p, encoding="utf-8").read() != text:
                bad.append(rel)
        else:
            os.makedirs(os.path.dirname(p), exist_ok=True)
            with open(p, "w", encoding="utf-8") as f:
                f.write(text)
    d = os.path.join(REPO, "docs", "reference")
    stale = ["docs/reference/" + n for n in sorted(os.listdir(d)) if "docs/reference/" + n not in files]
    if "--check" not in argv:  # drop reference pages of verbs that no longer exist
        for rel in stale:
            os.remove(os.path.join(REPO, rel))
        return 0
    bad += stale
    for rel in bad:
        print("out of date: " + rel, file=sys.stderr)
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
